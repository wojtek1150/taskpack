const ACTOR_NAMES: Record<Actor, string> = {
  user: 'User',
  'claude-code': 'Claude Code',
  claude: 'Claude',
  chatgpt: 'ChatGPT',
  codex: 'Codex',
  cursor: 'Cursor',
  other: 'Other',
};

/** Display name of an actor in the given language. */
export function actorName(actor: string, lang: Lang): string {
  return messages(lang).actor[actor as Actor] ?? ACTOR_NAMES[actor as Actor] ?? actor;
}
